"""Drive the full pure Plan A sweep across classes, one stage at a time.

Runs, per class: artefact check -> config -> baseline sanity -> full search ->
full-fidelity re-measurement -> anchor metrics -> Pareto figure. It shells out to
the same scripts used by hand for frog, ship and airplane; there is no search
logic here, deliberately, so a class run by this driver is the same experiment as
one run manually.

Two properties that matter over a four-hour run:

**Resumable.** Every stage checks for its own output first and skips if present.
A crash, a killed session or a machine restart costs the current stage, not the
sweep. ``--force`` re-runs anyway.

**It refuses to touch finished work.** Classes with an existing
``full_fidelity/front_full_fidelity.csv`` are skipped unless named explicitly,
so frog, ship and airplane cannot be overwritten by a careless invocation.

Selecting C*
------------
``C* = the front member maximising the anchor composite, ACC_r x (1 - ACC_f)``.

One rule for all ten classes, and it is the anchor paper's own metric rather
than something invented here. It was checked against the three classes already
reported by hand and reproduces every one: frog #8, ship #6, airplane #0. That
matters because ``evaluate_class_front.py``'s built-in rule -- minimise the
``D_f_test`` gap subject only to ``D_r_test > 0.80`` -- does *not* price retain
damage above that floor, and it picked a different member for ship.

Run::

    python experiments/run_class_sweep.py --classes 1,2,3,4,5,7,9
"""

from __future__ import annotations

import argparse
import csv
import json
import subprocess
import sys
import time
from pathlib import Path
from typing import Any

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT / "src"))

from medus_class.data import CIFAR10_CLASS_NAMES  # noqa: E402
from medus_class.utils.config import resolve_path  # noqa: E402

CONFIG_TEMPLATE = """# Plan A -- class unlearning of CIFAR-10 "{name}" (label {cid}).
#
# Part of the 10-class sweep. Every search setting below is DELIBERATELY
# IDENTICAL to plan_a_frog.yaml, plan_a_ship.yaml and plan_a_airplane.yaml, and
# duplicated rather than inherited so each class config is a self-contained
# record of what produced that class's result. A shared base would let an edit
# made for one class silently change another, and the ten rows would stop being
# comparable.
#
# Generated by experiments/run_class_sweep.py.

_base_:
  - base.yaml
  - data/cifar10_class.yaml
  - model/resnet18.yaml

# The data config defaults to frog. Overridden here -- deep_merge replaces these
# two keys and leaves the rest of the data config alone.
split:
  forget_class: {cid}
  split_file: results/splits/cifar10_class{cid}_{name}.json

evaluation:
  # The SAME W_0 as every other class: there is one original model and every
  # class is unlearned from it.
  checkpoint: results/checkpoints/cifar10_resnet18_seed42_best.pt

  # Retain-only reference, trained on D_r only. MUST be the _best_dr file,
  # selected on D_r_test accuracy with D_r_test loss as tie-breaker.
  reference_checkpoint: results/checkpoints/class{cid}_{name}_reference_best_dr.pt

  # --- objectives (fixed; there is no mode flag) ------------------------
  #   f1 = JS(P_ref(D_f) || P(D_f))    match the reference's distribution
  #   f2 = L_r                          retain loss
  #   f3 = ||dtheta|| / ||theta_0||     edit cost

  max_level: 2
  selection_rule: class_contrast

  forget_subset_size: 64
  retain_subset_size: 256

  measure_retain_test: false
  batch_size_key: train
  batch_cap: 3
  num_workers: 0

  compute_mia: true

search:
  name: plan_a_{name}
  algorithm: nsga2

  population_size: 10
  generations: 50
  seed: 42

  crossover_probability: 0.9
  mutation_probability: 0.10
  p_active: 0.5

  normalise_objectives: true
  cache_objectives: true
  checkpoint_every_generation: true

  results_dir: results/search/plan_a_{name}
"""


def composite(row: dict[str, str]) -> float:
    """The anchor's metric_function, in percent."""
    return 100.0 * float(row["retain_test_acc"]) * (1.0 - float(row["forget_test_acc"]))


def run(command: list[str], log: Path) -> int:
    """Run a stage, appending its output to the class log and to stdout."""
    print(f"    $ {' '.join(command[1:])}", flush=True)
    with log.open("a", encoding="utf-8") as handle:
        handle.write(f"\n{'=' * 100}\n$ {' '.join(command)}\n{'=' * 100}\n")
        handle.flush()
        return subprocess.run(command, cwd=str(PROJECT_ROOT),
                              stdout=handle, stderr=subprocess.STDOUT).returncode


def sweep_class(class_id: int, force: bool) -> dict[str, Any]:
    name = CIFAR10_CLASS_NAMES[class_id]
    run_dir = resolve_path(f"results/search/plan_a_{name}")
    front_csv = run_dir / "full_fidelity" / "front_full_fidelity.csv"
    log = resolve_path(f"results/plan_a_{name}_sweep.out")
    started = time.perf_counter()

    print(f"\n{'#' * 100}\n# class {class_id} ({name})\n{'#' * 100}", flush=True)

    # --- 1. artefacts -----------------------------------------------------
    required = {
        "W_0": resolve_path("results/checkpoints/cifar10_resnet18_seed42_best.pt"),
        "W_ref": resolve_path(
            f"results/checkpoints/class{class_id}_{name}_reference_best_dr.pt"),
        "split": resolve_path(f"results/splits/cifar10_class{class_id}_{name}.json"),
    }
    for label, path in required.items():
        if not path.is_file():
            return {"class_id": class_id, "name": name, "status": "FAILED",
                    "error": f"missing {label}: {path}"}
        print(f"    {label:<6} OK  {path.stat().st_size:>12,}  {path.name}")

    # --- 2. config --------------------------------------------------------
    config_path = PROJECT_ROOT / "configs" / "search" / f"plan_a_{name}.yaml"
    if not config_path.is_file():
        config_path.write_text(
            CONFIG_TEMPLATE.format(cid=class_id, name=name), encoding="utf-8")
        print(f"    config written  {config_path.name}")
    else:
        print(f"    config exists   {config_path.name}")
    config_arg = f"search/plan_a_{name}.yaml"

    if front_csv.is_file() and not force:
        print(f"    already complete -- {front_csv.relative_to(PROJECT_ROOT)} exists")
    else:
        # --- 3. baseline sanity -------------------------------------------
        code = run([sys.executable, "-u", "experiments/check_class_baselines.py",
                    "--config", config_arg, "--expect-class", str(class_id),
                    "--expect-reference-forget-test-acc", "0.0",
                    "--out", f"results/reference_training/{name}_baseline_check.md"], log)
        if code != 0:
            return {"class_id": class_id, "name": name, "status": "FAILED",
                    "error": f"baseline check failed (exit {code}); see {log.name}"}

        # --- 4. full search -----------------------------------------------
        if not (run_dir / "pareto_front.csv").is_file() or force:
            code = run([sys.executable, "-u", "experiments/run_plan_a.py",
                        "--config", config_arg], log)
            if code != 0:
                return {"class_id": class_id, "name": name, "status": "FAILED",
                        "error": f"search failed (exit {code}); see {log.name}"}

        # --- 5. full fidelity ---------------------------------------------
        code = run([sys.executable, "-u", "experiments/evaluate_class_front.py",
                    "--config", config_arg,
                    "--front", f"results/search/plan_a_{name}/pareto_front.csv"], log)
        if code != 0:
            return {"class_id": class_id, "name": name, "status": "FAILED",
                    "error": f"full-fidelity evaluation failed (exit {code})"}

    # --- 6. select C*, anchor metrics, figure -----------------------------
    with front_csv.open(encoding="utf-8-sig") as handle:
        front = [r for r in csv.DictReader(handle) if r["status"] == "ok"]
    star = max(front, key=composite)
    position = int(star["front_position"])
    print(f"    C* = front #{position}  {star['operators']}  "
          f"composite {composite(star):.2f}")

    anchor_csv = run_dir / f"{name}_anchor_metrics.csv"
    if not anchor_csv.is_file() or force:
        code = run([sys.executable, "-u", "experiments/report_anchor_metrics.py",
                    "--config", config_arg,
                    "--front", str(front_csv.relative_to(PROJECT_ROOT)).replace("\\", "/"),
                    "--front-position", str(position), "--best-s",
                    "--refined", f"results/search/plan_a_{name}/__no_refinement__.pt",
                    "--out-dir", f"results/search/plan_a_{name}",
                    "--label", name], log)
        if code != 0:
            return {"class_id": class_id, "name": name, "status": "FAILED",
                    "error": f"anchor metrics failed (exit {code})"}

    figure = run_dir / f"pareto_front_plan_a_{name}.png"
    if not figure.is_file() or force:
        run([sys.executable, "-u", "experiments/plot_pareto_front_class.py",
             "--class-id", str(class_id), "--run-dir", f"results/search/plan_a_{name}",
             "--selected", str(position)], log)

    # --- 7. the row -------------------------------------------------------
    summary = json.loads((run_dir / "summary.json").read_text(encoding="utf-8"))
    with anchor_csv.open(encoding="utf-8-sig") as handle:
        anchor = {r["model"]: r for r in csv.DictReader(handle)}
    star_row = anchor["C_star"]

    return {
        "class_id": class_id,
        "name": name,
        "status": "ok",
        "front_position": position,
        "operators": star["operators"],
        "front_size": len(front),
        "anchor_ACC_r": float(star_row["anchor_ACC_r"]),
        "anchor_ACC_f": float(star_row["anchor_ACC_f"]),
        "anchor_composite": float(star_row["anchor_composite"]),
        "anchor_MIA": float(star_row["anchor_MIA"]),
        "f1_js": float(star_row["f1_js"]),
        "f2_retain_train_loss": float(star_row["f2_retain_train_loss"]),
        "f3_edit_cost": float(star_row["f3_edit_cost"]),
        "selectivity_S": float(star_row["selectivity_S"]),
        "mia_auc": float(star_row["mia_auc"]),
        "forget_train_acc": float(star_row["forget_train_acc"]),
        "forget_test_acc": float(star_row["forget_test_acc"]),
        "retain_train_acc": float(star_row["retain_train_acc"]),
        "retain_test_acc": float(star_row["retain_test_acc"]),
        "W_0_ACC_r": float(anchor["W_0"]["anchor_ACC_r"]),
        "W_0_ACC_f": float(anchor["W_0"]["anchor_ACC_f"]),
        "W_ref_ACC_r": float(anchor["W_ref"]["anchor_ACC_r"]),
        "W_ref_ACC_f": float(anchor["W_ref"]["anchor_ACC_f"]),
        "search_evaluated": summary.get("evaluated"),
        "search_cache_hits": summary.get("cache_hits"),
        "search_failures": summary.get("failures"),
        "search_seconds": summary.get("elapsed_seconds"),
        "sweep_seconds": round(time.perf_counter() - started, 1),
        "results_dir": f"results/search/plan_a_{name}",
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--classes", required=True,
                        help="comma-separated class ids, e.g. 1,2,3,4,5,7,9")
    parser.add_argument("--force", action="store_true",
                        help="re-run stages whose output already exists")
    parser.add_argument("--out",
                        default="results/literature_alignment/sweep_progress.json")
    args = parser.parse_args()

    ids = [int(x) for x in args.classes.split(",") if x.strip()]
    out = resolve_path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    rows: list[dict[str, Any]] = []
    started = time.perf_counter()

    for class_id in ids:
        row = sweep_class(class_id, args.force)
        rows.append(row)
        # Written after every class, so a crash five classes in still leaves
        # five classes of results behind.
        out.write_text(json.dumps(rows, indent=2), encoding="utf-8")
        if row["status"] != "ok":
            print(f"    FAILED: {row['error']}", flush=True)
        else:
            print(f"    done in {row['sweep_seconds'] / 60:.1f} min  "
                  f"ACC_r {row['anchor_ACC_r']:.2f}  "
                  f"ACC_f {row['anchor_ACC_f']:.2f}  "
                  f"composite {row['anchor_composite']:.2f}  "
                  f"MIA {row['anchor_MIA']:.2f}  S {row['selectivity_S']:.2f}",
                  flush=True)

    ok = [r for r in rows if r["status"] == "ok"]
    print(f"\n{'=' * 100}")
    print(f"SWEEP COMPLETE -- {len(ok)}/{len(rows)} classes in "
          f"{(time.perf_counter() - started) / 60:.1f} min")
    print(f"  progress written to {out.relative_to(PROJECT_ROOT)}")
    print("=" * 100)
    return 0 if len(ok) == len(rows) else 1


if __name__ == "__main__":
    raise SystemExit(main())
